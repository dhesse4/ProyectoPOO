    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        
        Vehiculos vehiculoAdquirido = vehiculoSeleccionado();
        
        if (vehiculoAdquirido == null) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Selecciona un repuesto."
            );
            return;
        }

        StringBuilder mensaje = new StringBuilder();

        mensaje.append("Placa: ").append(vehiculoAdquirido.getPlaca())
               .append("\nMarca: ").append(vehiculoAdquirido.getMarca())
               .append("\nModelo: ").append(vehiculoAdquirido.getModelo())
               .append("\nMotor: ").append(vehiculoAdquirido.getMotor())
               .append("\nPrecio: Q. ").append(vehiculoAdquirido.getPrecio())
               .append("\nProcedencia: ")
               .append(vehiculoAdquirido.getAgencia()
                       ? "De agencia" : "De segunda mano");

        if (vehiculoAdquirido instanceof Automovil) {
            Automovil auto = (Automovil) vehiculoAdquirido;

            mensaje.append("\nTipo: Automóvil")
                   .append("\nTransmisión: ")
                   .append(auto.getAutomatico() ? "Automática" : "Manual")
                   .append("\nCombustible: ")
                   .append(auto.getElectrico() ? "Eléctrico" : "Gasolina");

        } else if (vehiculoAdquirido instanceof Motocicleta) {
            Motocicleta moto = (Motocicleta) vehiculoAdquirido;

            mensaje.append("\nTipo: Motocicleta")
                   .append("\nTipo de moto: ").append(moto.getTipo())
                   .append("\nCilindraje: ").append(moto.getCilindraje()).append(" CC");
        }

        mensaje.append("\n\nTotal: Q. ")
       .append(String.format("%.2f", vehiculoAdquirido.getPrecio()))
       .append("\n\n¿Confirmar la venta?");

        int respuesta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            mensaje.toString(),
            "Confirmar venta",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.QUESTION_MESSAGE
        );
        
        if (respuesta == javax.swing.JOptionPane.YES_OPTION) 
        {
            datos.getVehiculos().remove(vehiculoAdquirido);
            javax.swing.JOptionPane.showMessageDialog(
                this, "Gracias por tu compra!!!."
            );
            
            for (Vehiculos vehiculo : DatosAgencia.getInstancia().getVehiculos()) 
            {

                if(vehiculo != null)
                {
                    ((javax.swing.JComboBox) opcionesVehiculos).addItem(vehiculo);
                }
            }

            opcionesVehiculos.setSelectedIndex(-1);
            
             javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tablaVehiculo.getModel();

            modelo.setRowCount(0);
        }

    }//GEN-LAST:event_jButton2ActionPerformed

