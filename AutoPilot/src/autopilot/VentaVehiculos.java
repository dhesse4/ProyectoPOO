    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        Vehiculos elegido = vehiculoSeleccionado();

        if (elegido == null) {
            return; // No hay ningún vehículo seleccionado
        }

        javax.swing.table.DefaultTableModel modelo =
        (javax.swing.table.DefaultTableModel) tablaVehiculo.getModel();

        modelo.setRowCount(0); // Borra los datos del vehículo anterior

        modelo.addRow(new Object[]{"Placa", elegido.getPlaca()});
        modelo.addRow(new Object[]{"Marca", elegido.getMarca()});
        modelo.addRow(new Object[]{"Modelo", elegido.getModelo()});
        modelo.addRow(new Object[]{"Motor", elegido.getMotor()});
        modelo.addRow(new Object[]{"Precio", "Q. " + elegido.getPrecio()});
        modelo.addRow(new Object[]{
            "Procedencia",
            elegido.getAgencia() ? "De agencia" : "De segunda mano"
        });
        modelo.addRow(new Object[]{
            "Último mantenimiento",
            elegido.getUltMantenimiento().format(
                java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy")
            )
        });

        if (elegido instanceof Automovil) {
            Automovil auto = (Automovil) elegido;

            modelo.addRow(new Object[]{"Tipo de vehículo", "Automóvil"});
            modelo.addRow(new Object[]{
                "Transmisión",
                auto.getAutomatico() ? "Automática" : "Mecánica / manual"
            });
            modelo.addRow(new Object[]{
                "Combustible",
                auto.getElectrico() ? "Eléctrico" : "Gasolina"
            });

        } else if (elegido instanceof Motocicleta) {
            Motocicleta moto = (Motocicleta) elegido;

            modelo.addRow(new Object[]{"Tipo de vehículo", "Motocicleta"});
            modelo.addRow(new Object[]{"Tipo de moto", moto.getTipo()});
            modelo.addRow(new Object[]{
                "Cilindraje",
                String.valueOf(moto.getCilindraje()) + " CC"
            });
        }
    }//GEN-LAST:event_jButton1ActionPerformed

