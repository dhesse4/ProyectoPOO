    private void cargarAnuncios() {
    jPanel2.removeAll();
    jPanel2.setLayout(new javax.swing.BoxLayout(
        jPanel2,
        javax.swing.BoxLayout.Y_AXIS
    ));
    jPanel2.setBackground(new java.awt.Color(242, 245, 249));
    jPanel2.setBorder(
        javax.swing.BorderFactory.createEmptyBorder(14, 14, 14, 14)
    );

    if (DatosAgencia.getInstancia().getAnuncios().isEmpty()) {
        jLabel2.setText("Todavía no hay anuncios");
        jLabel3.setText("Sé la primera persona en publicar uno.");

        jLabel2.setAlignmentX(java.awt.Component.CENTER_ALIGNMENT);
        jLabel3.setAlignmentX(java.awt.Component.CENTER_ALIGNMENT);

        jPanel2.add(javax.swing.Box.createVerticalGlue());
        jPanel2.add(jLabel2);
        jPanel2.add(javax.swing.Box.createVerticalStrut(8));
        jPanel2.add(jLabel3);
        jPanel2.add(javax.swing.Box.createVerticalGlue());

    } else {
        for (Anuncio anuncio
                : DatosAgencia.getInstancia().getAnuncios()) {

            javax.swing.JPanel tarjeta = new javax.swing.JPanel();
            tarjeta.setLayout(new javax.swing.BoxLayout(
                tarjeta,
                javax.swing.BoxLayout.Y_AXIS
            ));
            tarjeta.setBackground(java.awt.Color.WHITE);
            tarjeta.setBorder(
                javax.swing.BorderFactory.createCompoundBorder(
                    javax.swing.BorderFactory.createLineBorder(
                        new java.awt.Color(210, 218, 228)
                    ),
                    javax.swing.BorderFactory.createEmptyBorder(
                        14, 16, 14, 16
                    )
                )
            );
            tarjeta.setAlignmentX(java.awt.Component.LEFT_ALIGNMENT);

            // Nombre de quien publicó: aparece primero.
            String nombre = anuncio.getUsuario();

            if (nombre == null || nombre.trim().isEmpty()) {
                nombre = "Usuario";
            }

            javax.swing.JLabel autor = new javax.swing.JLabel(nombre);
            autor.setFont(new java.awt.Font(
                "Segoe UI", java.awt.Font.BOLD, 16
            ));
            autor.setForeground(new java.awt.Color(0, 51, 153));
            autor.setAlignmentX(java.awt.Component.LEFT_ALIGNMENT);
            tarjeta.add(autor);

            javax.swing.JLabel tipo = new javax.swing.JLabel(
                "Publicación · " + anuncio.getTipo()
            );
            tipo.setFont(new java.awt.Font(
                "Segoe UI", java.awt.Font.PLAIN, 12
            ));
            tipo.setForeground(new java.awt.Color(105, 115, 130));
            tipo.setAlignmentX(java.awt.Component.LEFT_ALIGNMENT);
            tarjeta.add(tipo);

            tarjeta.add(javax.swing.Box.createVerticalStrut(10));

            if (anuncio.getTitulo() != null
                    && !anuncio.getTitulo().trim().isEmpty()
                    && !anuncio.getTitulo().equals("Anuncio")) {

                javax.swing.JLabel titulo = new javax.swing.JLabel(
                    escaparHtml(anuncio.getTitulo())
                );
                titulo.setFont(new java.awt.Font(
                    "Segoe UI", java.awt.Font.BOLD, 17
                ));
                titulo.setForeground(new java.awt.Color(35, 40, 48));
                titulo.setAlignmentX(java.awt.Component.LEFT_ALIGNMENT);
                tarjeta.add(titulo);
                tarjeta.add(javax.swing.Box.createVerticalStrut(5));
            }

            if (anuncio.getDescripcion() != null
                    && !anuncio.getDescripcion().trim().isEmpty()) {

                String texto = escaparHtml(anuncio.getDescripcion())
                    .replace("\n", "<br>");

                javax.swing.JLabel descripcion =
                    new javax.swing.JLabel(
                        "<html><div style='width:520px;'>"
                        + texto
                        + "</div></html>"
                    );
                descripcion.setFont(new java.awt.Font(
                    "Segoe UI", java.awt.Font.PLAIN, 14
                ));
                descripcion.setForeground(new java.awt.Color(55, 60, 68));
                descripcion.setAlignmentX(
                    java.awt.Component.LEFT_ALIGNMENT
                );
                tarjeta.add(descripcion);
            }

            if (anuncio.getPrecio() != null) {
                tarjeta.add(javax.swing.Box.createVerticalStrut(10));

                javax.swing.JLabel precio = new javax.swing.JLabel(
                    "Q " + String.format("%.2f", anuncio.getPrecio())
                );
                precio.setFont(new java.awt.Font(
                    "Segoe UI", java.awt.Font.BOLD, 15
                ));
                precio.setForeground(new java.awt.Color(0, 102, 153));
                precio.setAlignmentX(java.awt.Component.LEFT_ALIGNMENT);
                tarjeta.add(precio);
            }

            tarjeta.add(javax.swing.Box.createVerticalStrut(10));
            tarjeta.add(new javax.swing.JSeparator());

            // Área donde se muestran los comentarios de este anuncio.
            javax.swing.JPanel panelComentarios =
                new javax.swing.JPanel();
            panelComentarios.setLayout(new javax.swing.BoxLayout(
                panelComentarios,
                javax.swing.BoxLayout.Y_AXIS
            ));
            panelComentarios.setBackground(java.awt.Color.WHITE);
            panelComentarios.setAlignmentX(
                java.awt.Component.LEFT_ALIGNMENT
            );

            if (anuncio.getComentarios().isEmpty()) {
                javax.swing.JLabel sinComentarios =
                    new javax.swing.JLabel("Todavía no hay comentarios");
                sinComentarios.setFont(new java.awt.Font(
                    "Segoe UI", java.awt.Font.ITALIC, 12
                ));
                sinComentarios.setForeground(java.awt.Color.GRAY);
                panelComentarios.add(sinComentarios);
            } else {
                for (String comentario : anuncio.getComentarios()) {
                    javax.swing.JLabel textoComentario =
                        new javax.swing.JLabel(escaparHtml(comentario));
                    textoComentario.setFont(new java.awt.Font(
                        "Segoe UI", java.awt.Font.PLAIN, 13
                    ));
                    panelComentarios.add(textoComentario);
                }
            }

            javax.swing.JTextField campoComentario =
                new javax.swing.JTextField();
            campoComentario.setToolTipText("Escribe un comentario");

            javax.swing.JButton botonComentar =
                new javax.swing.JButton("Comentar");

            javax.swing.JPanel filaComentario =
                new javax.swing.JPanel(
                    new java.awt.BorderLayout(8, 0)
                );
            filaComentario.setBackground(java.awt.Color.WHITE);
            filaComentario.add(
                campoComentario,
                java.awt.BorderLayout.CENTER
            );
            filaComentario.add(
                botonComentar,
                java.awt.BorderLayout.EAST
            );

            botonComentar.addActionListener(e -> {
                String texto = campoComentario.getText().trim();

                if (!texto.isEmpty()) {
                    anuncio.agregarComentario("Tú: " + texto);
                    cargarAnuncios();
                }
            });

            tarjeta.add(javax.swing.Box.createVerticalStrut(8));
            tarjeta.add(panelComentarios);
            tarjeta.add(javax.swing.Box.createVerticalStrut(8));
            tarjeta.add(filaComentario);

            tarjeta.setMaximumSize(new java.awt.Dimension(
                Integer.MAX_VALUE,
                tarjeta.getPreferredSize().height
            ));

            jPanel2.add(tarjeta);
            jPanel2.add(javax.swing.Box.createVerticalStrut(12));
        }
    }

    jPanel2.revalidate();
    jPanel2.repaint();
}

    private String escaparHtml(String texto) {
         return texto.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;");
}
