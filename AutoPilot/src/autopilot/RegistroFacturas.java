    private void actualizarOpcionesFactura() 
    {
        jComboBox1.removeAllItems();

        for (Factura factura : datos.getFacturas()) 
        {
            ((javax.swing.JComboBox) jComboBox1).addItem(factura);
        }

        jComboBox1.setSelectedIndex(-1);
    }

