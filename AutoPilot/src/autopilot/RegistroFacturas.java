    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        Factura elegido = facturaSeleccionada();

        if (elegido == null) {
            return; // No hay ninguna factura seleccionada.
        }

        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel) jTable1.getModel();

        modelo.setRowCount(0);
        modelo.setColumnIdentifiers(
                new String[]{"Característica", "Valor"}
        );

        modelo.addRow(new Object[]{"Número", elegido.getNumero()});
        modelo.addRow(new Object[]{"Fecha", elegido.getFecha()});
        modelo.addRow(new Object[]{"Cliente", elegido.getCliente()});
        modelo.addRow(new Object[]{"Usuario", elegido.getUsuario()});
        modelo.addRow(new Object[]{"Descripción", elegido.getDescripcion()});
        modelo.addRow(new Object[]{"Cantidad", elegido.getCantidad()});

        modelo.addRow(new Object[]{
            "Precio unitario",
            String.format(
                    java.util.Locale.US,
                    "Q %,.2f",
                    elegido.getPrecioUnitario()
            )
        });

        modelo.addRow(new Object[]{
            "Total",
            String.format(
                    java.util.Locale.US,
                    "Q %,.2f",
                    elegido.getTotal()
            )
        });
    }//GEN-LAST:event_jButton1ActionPerformed

