    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
        String placa = placaTxt1.getText();
        boolean encontrado = false;
        Vehiculos seleccionado = null;
        
        for(Vehiculos vehiculo : DatosAgencia.getInstancia().getVehiculos())
        {
            if(placa.equals(vehiculo.getPlaca()))
            {
                encontrado = true;
                seleccionado = vehiculo;
            }
        }
        
        if(encontrado)
        {
            javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();

            modelo.setRowCount(0); // Borra los datos del vehículo anterior

            modelo.addRow(new Object[]{
            "Último mantenimiento",
            seleccionado.getUltMantenimiento().format(
                java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy")
            )
            });
            
            modelo.addRow(new Object[]{
            "Proximo mantenimiento",
            seleccionado.getProxMantenimiento().format(
                java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy")
            )
            });
        }
        else
        {
            javax.swing.JOptionPane.showMessageDialog(
                this, "No se ha encontrado un vehiculo con esta placa."
            );
            return;
        }
            
        
    }//GEN-LAST:event_jButton1ActionPerformed

