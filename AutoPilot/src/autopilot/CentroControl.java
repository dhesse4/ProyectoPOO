    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
        jComboBox2.removeAllItems();

        Object seleccion = jComboBox1.getSelectedItem();

        if (seleccion == null) {
            return;
        }

        DatosAgencia datos = DatosAgencia.getInstancia();

        switch (seleccion.toString()) {
            case "Seguros":
                for (Seguros seguro : datos.getSeguros()) {
                    jComboBox2.addItem(seguro);
                }
                break;

            case "Talleres":
                for (Taller taller : datos.getTalleres()) {
                    jComboBox2.addItem(taller);
                }
                break;

            case "Empleados":
                for (Empleado empleado : datos.getEmpleados()) {
                    jComboBox2.addItem(empleado);
                }
                break;

            case "Anuncios":
                for (Anuncio anuncio : datos.getAnuncios()) {
                    jComboBox2.addItem(anuncio);
                }
                break;

            case "Repuestos":
                for (Repuesto repuesto : datos.getRepuestos()) {
                    jComboBox2.addItem(repuesto);
                }
                break;

            case "Usuarios":
                for (Usuario usuario : datos.getUsuarios()) {
                    jComboBox2.addItem(usuario);
                }
                break;
        }
    
        
    }//GEN-LAST:event_jButton1ActionPerformed

