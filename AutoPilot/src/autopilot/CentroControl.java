    private void cargarObjetos() {
        try {
            datos.verificarAccesoAdministrador();

        } catch (SecurityException e) {
            jComboBox2.removeAllItems();
            btnAplicar.setEnabled(false);

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage()
            );

            dispose();
            return;
        }

        jComboBox2.removeAllItems();

        String clase = (String) jComboBox1.getSelectedItem();

        if (clase == null) {
            return;
        }

        switch (clase) {
            case "Seguros" ->
                datos.getSeguros().forEach(jComboBox2::addItem);

            case "Talleres" ->
                datos.getTalleres().forEach(jComboBox2::addItem);

            case "Anuncios" ->
                datos.getAnuncios().forEach(jComboBox2::addItem);

            case "Repuestos" ->
                datos.getRepuestos().forEach(jComboBox2::addItem);

            case "Usuarios" ->
                datos.getUsuarios().forEach(jComboBox2::addItem);
        }

        jComboBox2.setSelectedIndex(-1);
        btnAplicar.setEnabled(jComboBox2.getItemCount() > 0);
    }

    private String textoObjeto(Object objeto) {
        if (objeto instanceof Anuncio anuncio) {
            return anuncio.getTitulo()
                    + " - " + anuncio.getUsuario();
        }

        if (objeto instanceof Seguros seguro) {
            return seguro.getAseguradora()
                    + " - " + seguro.getTipo();
        }

        if (objeto instanceof Taller taller) {
            return taller.getId() + " - " + taller.getNombre();
        }

        if (objeto instanceof Repuesto repuesto) {
            return repuesto.getNombre()
                    + " - " + repuesto.getMarca()
                    + " | Stock: " + repuesto.getStock();
        }

        if (objeto instanceof Usuario usuario) {
            return usuario.getUsuario()
                    + (usuario.getAdmin()
                            ? " - Administrador"
                            : " - Usuario normal");
        }

        return objeto == null ? "" : objeto.toString();
    }

    private void configurarPresentacionObjetos() {
        jComboBox2.setRenderer(
                new javax.swing.DefaultListCellRenderer() {

            @Override
            public java.awt.Component getListCellRendererComponent(
                    javax.swing.JList<?> lista,
                    Object valor,
                    int indice,
                    boolean seleccionado,
                    boolean tieneFoco) {

                super.getListCellRendererComponent(
                        lista,
                        valor,
                        indice,
                        seleccionado,
                        tieneFoco
                );

                setText(textoObjeto(valor));
                return this;
            }
        });
    }
    
    private void gestionarSeleccion() {
        try {
            datos.verificarAccesoAdministrador();

            Object seleccionado = jComboBox2.getSelectedItem();

            if (seleccionado == null) {
                throw new IllegalArgumentException(
                        "Selecciona un objeto."
                );
            }

            if (seleccionado instanceof Anuncio
                    || seleccionado instanceof Taller
                    || seleccionado instanceof Seguros) {

                int respuesta =
                        javax.swing.JOptionPane.showConfirmDialog(
                                this,
                                "¿Eliminar este registro?\n"
                                        + textoObjeto(seleccionado),
                                "Confirmar eliminación",
                                javax.swing.JOptionPane.YES_NO_OPTION,
                                javax.swing.JOptionPane.WARNING_MESSAGE
                        );

                if (respuesta != javax.swing.JOptionPane.YES_OPTION) {
                    return;
                }

                if (seleccionado instanceof Anuncio anuncio) {
                    datos.eliminarAnuncio(anuncio);

                } else if (seleccionado instanceof Taller taller) {
                    datos.eliminarTaller(taller);

                } else if (seleccionado instanceof Seguros seguro) {
                    datos.eliminarSeguro(seguro);
                }

            } else if (seleccionado instanceof Repuesto repuesto) {
                javax.swing.JSpinner stock =
                        new javax.swing.JSpinner(
                                new javax.swing.SpinnerNumberModel(
                                        repuesto.getStock(),
                                        0,
                                        Integer.MAX_VALUE,
                                        1
                                )
                        );

                int respuesta =
                        javax.swing.JOptionPane.showConfirmDialog(
                                this,
                                new Object[]{
                                    textoObjeto(repuesto),
                                    "Nuevo stock total:",
                                    stock
                                },
                                "Modificar stock",
                                javax.swing.JOptionPane.OK_CANCEL_OPTION
                        );

                if (respuesta != javax.swing.JOptionPane.OK_OPTION) {
                    return;
                }

                stock.commitEdit();

                int nuevoStock = ((Number) stock.getValue()).intValue();

                datos.actualizarStockRepuesto(
                        repuesto, nuevoStock
                );

            } else if (seleccionado instanceof Usuario usuario) {
                javax.swing.JCheckBox permiso =
                        new javax.swing.JCheckBox(
                                "Es administrador",
                                usuario.getAdmin()
                        );

                int respuesta =
                        javax.swing.JOptionPane.showConfirmDialog(
                                this,
                                new Object[]{
                                    "Cuenta: " + usuario.getUsuario(),
                                    permiso
                                },
                                "Cambiar permiso",
                                javax.swing.JOptionPane.OK_CANCEL_OPTION
                        );

                if (respuesta != javax.swing.JOptionPane.OK_OPTION) {
                    return;
                }

                if (permiso.isSelected() == usuario.getAdmin()) {
                    javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "No se realizaron cambios."
                    );
                    return;
                }

                datos.cambiarPermisoUsuario(
                        usuario, permiso.isSelected()
                );

            } else {
                throw new IllegalArgumentException(
                        "No hay una acción para este objeto."
                );
            }

            cargarObjetos();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "La operación se guardó correctamente."
            );

        } catch (java.text.ParseException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Introduce un stock entero mayor o igual a cero."
            );

        } catch (IllegalArgumentException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage()
            );

        } catch (SecurityException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage()
            );

            dispose();

        } catch (java.io.IOException e) {
            logger.log(
                    java.util.logging.Level.SEVERE,
                    "Error al guardar desde el centro de control",
                    e
            );

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se pudo completar el guardado.\n"
                            + e.getMessage(),
                    "Error de guardado",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }
    
