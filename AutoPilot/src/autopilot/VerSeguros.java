private void prepararTabla() {
    DefaultTableModel modelo = new DefaultTableModel(
        new Object[]{"Dato", "Información"}, 0
    ) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };

    jTable1.setModel(modelo);

    jTable1.getColumnModel().getColumn(0).setCellRenderer(
        new DefaultTableCellRenderer() {
            @Override
            public Component getTableCellRendererComponent(
                    javax.swing.JTable tabla, Object valor,
                    boolean seleccionado, boolean tieneFoco,
                    int fila, int columna) {

                Component celda = super.getTableCellRendererComponent(
                    tabla, valor, seleccionado, tieneFoco, fila, columna
                );
                celda.setForeground(new Color(0, 51, 153));
                return celda;
            }
        }
    );
}

private void cargarListaSeguros() {
    jComboBox2.removeAllItems();

    for (Seguros seguro : DatosAgencia.getInstancia().getSeguros()) {
        jComboBox2.addItem(seguro.getAseguradora());
    }

    mostrarSeguroSeleccionado();
}

private void mostrarSeguroSeleccionado() {
    DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
    modelo.setRowCount(0);

    String aseguradoraElegida =
            (String) jComboBox2.getSelectedItem();

    if (aseguradoraElegida == null) {
        return;
    }

    for (Seguros seguro : DatosAgencia.getInstancia().getSeguros()) {
        if (seguro.getAseguradora().equals(aseguradoraElegida)) {
            modelo.addRow(new Object[]{"Aseguradora", seguro.getAseguradora()});
            modelo.addRow(new Object[]{"Precio", "Q " + seguro.getPrecio()});
            modelo.addRow(new Object[]{"Tipo", seguro.getTipo()});
            modelo.addRow(new Object[]{"Cobertura", seguro.getCobertura()});
            break;
        }
    }
}
     
