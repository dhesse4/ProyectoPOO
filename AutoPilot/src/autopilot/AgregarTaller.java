    public Empleado empleadoSeleccionado()
    {
        Empleado seleccionado = (Empleado) gerenteCombo.getSelectedItem();

        if (seleccionado != null)
        {
            return seleccionado;
        }
        else
        {
            return null;
        }
    }
    
