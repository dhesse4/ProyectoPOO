    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        
        Taller elegido = tallerSeleccionado();

        if (elegido == null) {
            return; // No hay ningún taller seleccionado
        }

        javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();

        modelo.setRowCount(0); // Borra los datos del taller anterior

        modelo.addRow(new Object[]{"ID", elegido.getId()});
        modelo.addRow(new Object[]{"Nombre", elegido.getNombre()});
        modelo.addRow(new Object[]{"Dirección", elegido.getDireccion()});
        modelo.addRow(new Object[]{"Teléfono", elegido.getTelefono()});
        modelo.addRow(new Object[]{"Correo", elegido.getCorreo()});
        modelo.addRow(new Object[]{"Horario", elegido.getHorario()});

        Empleado gerente = elegido.getGerente();

        modelo.addRow(new Object[]{
            "Gerente",
            gerente != null
                ? gerente.getNombre() + " " + gerente.getApellido()
                : "Sin gerente asignado"
        });

        modelo.addRow(new Object[]{
            "Rating promedio",
            elegido.getCantidadResenas() > 0
                ? String.format("%.1f / 5", elegido.getRatingPromedio())
                : "Sin calificaciones"
        });

        modelo.addRow(new Object[]{
            "Cantidad de reseñas", elegido.getCantidadResenas()
        });

        modelo.addRow(new Object[]{
            "Estado", elegido.isActivo() ? "Activo" : "Inactivo"
        });
        
    }//GEN-LAST:event_jButton4ActionPerformed

