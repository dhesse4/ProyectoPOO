    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        // TODO add your handling code here:
        
        Empleado elegido = empleadoSeleccionado();

        if (elegido == null) {
            return; // No hay ningún empleado seleccionado
        }

        javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();

        modelo.setRowCount(0); // Borra los datos del empleado anterior

        modelo.addRow(new Object[]{"ID", elegido.getId()});
        modelo.addRow(new Object[]{"Nombre", elegido.getNombre()});
        modelo.addRow(new Object[]{"Apellido", elegido.getApellido()});
        modelo.addRow(new Object[]{"Teléfono", elegido.getTelefono()});

        modelo.addRow(new Object[]{
            "Estado", elegido.isActivo() ? "Activo" : "Inactivo"
        });
        
        
    }//GEN-LAST:event_jButton5ActionPerformed

